# Estructura de condición Switch

promedio = 5

match promedio:
    case 5:
        print('No alcano el mínimo requerido')
    case 6:
        print('Satisfactorio')
    case 7:
        print('Regular')
    case 8:
        print('Bueno')
    case 9:
        print('Muy Bueno')
    case 10:
        print('Excelente')
    