''' Hacer un programa que calcule el promedio de 5 calificaciones e imprima el resultado obtenido. '''

calificacionUno = float(input('Introduce calificación: '))
calificacionDos = float(input('Introduce calificación: '))
calificacionTres = float(input('Introduce calificación: '))
calificacionCuatro = float(input('Introduce calificación: '))
calificacionCinco = float(input('Introduce calificación: '))
promedio = ( calificacionUno + calificacionDos + calificacionTres + calificacionCuatro + calificacionCinco ) / 5

print(f'El Promedio es: {promedio}')



